import hashlib

from src.enums import OperatorType, TemplatePackId

PACK_COUNT = 5


def get_template_pack_id(pair_seed: int) -> TemplatePackId:
    digest = hashlib.sha256(f"template_pack:{pair_seed}".encode()).digest()
    pack_id = int.from_bytes(digest[:8], "big") % PACK_COUNT
    return TemplatePackId(f"pack_{pack_id:02d}")


